#!/usr/bin/env python
"""Build the ONE file you drop into Colab (run on your own machine, from anywhere):

    python colab/build_hub.py                  ->  dist/nisar_hub.pyz     (~0.5 MB: engine + config + the hub page)

Everything is taken from this repo automatically, including your Earthdata token from <repo>/.env (EARTHDATA_TOKEN=...),
so Colab does not ask for it. That makes the .pyz SECRET: keep it off public drives, repos and chats (dist/ is git-ignored).

Upload it to /content in Colab and run, in a notebook cell:

    import runpy; runpy.run_path("/content/nisar_hub.pyz", run_name="__main__")

First run: unpacks next to itself (/content/nisar-hub), pip-installs what Colab lacks, takes the token from the packed .env
(none packed: Colab Secrets `EARTHDATA_TOKEN`, else a hidden prompt), opens a tunnel and prints one link. Open it: type a
latitude / longitude / size, see the tiles, download, browse every stored layer. Data lands in /content/datasets.

Options
    --no-env        do NOT pack <repo>/.env: Colab then reads EARTHDATA_TOKEN from Secrets or asks. Use this for a file
                    you want to share. Only the root .env is ever packed, never any other .env*.
    --wheels        also pack the pinned dependencies as wheels (~90 MB, needs network here): Colab installs
                    from them first and only asks PyPI for what is missing. Not needed for normal use.
    --py 3.12       Python version of the Colab runtime the wheels are for (default 3.12; a mismatch only means
                    pip ignores them and uses PyPI).
    --out PATH      where to write it (default dist/nisar_hub.pyz)

Notebook options: set NISAR_HUB_ARGS before the cell, e.g. os.environ["NISAR_HUB_ARGS"] = "--port 8901".
Unpack without launching:  !python /content/nisar_hub.pyz --extract-only
"""
from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(HERE))
from build_colab_zip import _has_credentials  # noqa: E402  (same credential check as the full-repo zip)

OUT = ROOT / "dist" / "nisar_hub.pyz"
REQUIREMENTS = ("requirements-retrieval.txt", "requirements-engine.txt")
ROOT_FILES = ("pyproject.toml", *REQUIREMENTS)                       # pyproject.toml: how the engine finds its root
COLAB_FILES = ("nisar_colab.py", "hub.py", "hub_page.html")
TREES = ("engine", "config")                                        # whole folders, minus the junk below
EXTRA_PY = ("tools/debug_hub",)                                     # engine.api.background imports it lazily; *.py only
SKIP_DIRS = {"__pycache__", "tests", ".pytest_cache"}
SKIP_SUFFIXES = (".pyc", ".pyo")

# The entry point inside the .pyz. Plain Python, no dependencies: unpack once per build, then run colab/hub.py.
MAIN = r'''# nisar_hub.pyz entry point (generated by colab/build_hub.py; do not edit)
import importlib.util
import os
import shlex
import shutil
import sys
import zipfile
from pathlib import Path


def _archive() -> Path:
    p = Path(__file__).resolve()
    while p != p.parent and not p.is_file():                # __file__ may be <archive>/__main__.py
        p = p.parent
    return p


def _home() -> Path:
    if os.environ.get("NISAR_HUB_HOME"):
        return Path(os.environ["NISAR_HUB_HOME"])
    return (Path("/content") if Path("/content").is_dir() else Path.home()) / "nisar-hub"


def unpack(archive: Path, home: Path) -> bool:
    """Extract once per build (BUILD_ID is a hash of the contents). Returns True if it unpacked."""
    with zipfile.ZipFile(archive) as z:
        build = z.read("BUILD_ID").decode().strip()
        stamp = home / ".build_id"
        if stamp.is_file() and stamp.read_text().strip() == build and (home / "engine").is_dir():
            return False
        for top in {n.split("/")[0] for n in z.namelist() if "/" in n}:
            shutil.rmtree(home / top, ignore_errors=True)    # old code goes; files like .env are never touched
        home.mkdir(parents=True, exist_ok=True)
        for info in z.infolist():
            if info.filename not in ("__main__.py", "BUILD_ID"):
                z.extract(info, home)
        stamp.write_text(build)
    return True


def main() -> int:
    in_kernel = "ipykernel" in sys.modules
    argv = shlex.split(os.environ.get("NISAR_HUB_ARGS", "")) if in_kernel else sys.argv[1:]   # a kernel's argv is not ours
    home = _home()
    print(f"NISAR hub: {'unpacked into' if unpack(_archive(), home) else 'already unpacked in'} {home}", flush=True)
    if "--extract-only" in argv:
        return 0
    spec = importlib.util.spec_from_file_location("nisar_hub", home / "colab" / "hub.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["nisar_hub"] = mod
    spec.loader.exec_module(mod)
    return mod.main(argv)


rc = main()
if "ipykernel" not in sys.modules:
    sys.exit(rc)
if rc:
    print(f"(the hub did not start: exit code {rc}; the message above says why)")
'''


def _env_names(env: Path) -> list[str]:
    """KEY names of a .env file, never the values."""
    out = []
    for line in env.read_text(encoding="utf-8-sig").splitlines():
        line = line.strip().removeprefix("export ").strip()
        if line and not line.startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            if v.strip().strip("\"'"):
                out.append(k.strip())
    return out


def _is_secret_env(name: str) -> bool:
    return (name == ".env" or name.startswith(".env.")) and name != ".env.example"


def _walk(base: Path, only_py: bool = False):
    for p in sorted(base.rglob("*")):
        rel = p.relative_to(base)
        if not p.is_file() or any(part in SKIP_DIRS for part in rel.parts[:-1]):
            continue
        if p.name.endswith(SKIP_SUFFIXES) or _is_secret_env(p.name) or (only_py and p.suffix != ".py"):
            continue
        yield p


def select(root: Path = ROOT) -> list[tuple[str, Path]]:
    """(archive name, source file) for everything the hub needs. Anything not listed here is not shipped."""
    out: list[tuple[str, Path]] = []
    for tree in TREES:
        out += [(p.relative_to(root).as_posix(), p) for p in _walk(root / tree)]
    for tree in EXTRA_PY:
        if (root / tree).is_dir():
            out += [(p.relative_to(root).as_posix(), p) for p in _walk(root / tree, only_py=True)]
    out += [(f"colab/{n}", root / "colab" / n) for n in COLAB_FILES]
    out += [(n, root / n) for n in ROOT_FILES if (root / n).is_file()]
    missing = [a for a, p in out if not p.is_file()]
    if missing:
        raise FileNotFoundError(f"cannot build the hub, missing: {', '.join(missing)}")
    return out


def download_wheels(dest: Path, root: Path, py: str) -> int:
    """pip-download the pinned requirements as Linux x86-64 wheels for Colab's Python. Returns the count."""
    dest.mkdir(parents=True, exist_ok=True)
    cmd = [sys.executable, "-m", "pip", "download", "-q", "-d", str(dest), "--only-binary=:all:",
           "--python-version", py, "--implementation", "cp", "--platform", "manylinux2014_x86_64",
           "--platform", "manylinux_2_28_x86_64", "--platform", "manylinux_2_17_x86_64"]
    for name in REQUIREMENTS:
        cmd += ["-r", str(root / name)]
    subprocess.run(cmd, check=True)
    return len(list(dest.glob("*.whl")))


def build(out: Path = OUT, *, root: Path = ROOT, include_env: bool = False, wheels: bool = False, py: str = "3.12") -> Path:
    files = select(root)
    env_file = None
    if include_env:
        env_file = root / ".env"
        if not env_file.is_file():
            print("WARNING: --include-env but there is no .env at the repo root; no credentials are packed.")
            env_file = None
        elif not _has_credentials(env_file):
            print("WARNING: .env has no EARTHDATA_TOKEN (or username + password). Colab will fall back to Secrets / a prompt.")
    with tempfile.TemporaryDirectory() as tmp:
        if wheels:
            n = download_wheels(Path(tmp) / "wheelhouse", root, py)
            print(f"wheelhouse: {n} wheels for Python {py} / Linux x86-64")
            files += [(f"wheelhouse/{p.name}", p) for p in sorted((Path(tmp) / "wheelhouse").glob("*.whl"))]
        if env_file is not None:
            files.append((".env", env_file))
        h = hashlib.sha256()
        for arc, p in files:
            h.update(arc.encode())
            h.update(p.read_bytes())
        out = Path(out)
        out.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
            z.writestr("__main__.py", MAIN)
            z.writestr("BUILD_ID", h.hexdigest()[:16] + "\n")
            for arc, p in files:
                z.write(p, arc)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--no-env", action="store_true", help="do not pack the repo's .env")
    ap.add_argument("--include-env", action="store_true", help=argparse.SUPPRESS)      # old spelling; packing is the default now
    ap.add_argument("--wheels", action="store_true")
    ap.add_argument("--py", default="3.12")
    a = ap.parse_args(argv)
    pack_env = not a.no_env
    if not pack_env:
        print("No .env packed (--no-env). In Colab: add EARTHDATA_TOKEN under Secrets, or type it at the hidden prompt.")
    elif not (ROOT / ".env").is_file():
        print("No .env at the repo root, so no token is packed. In Colab: add EARTHDATA_TOKEN under Secrets, or type it at the "
              "hidden prompt. (Put EARTHDATA_TOKEN=... in .env here and rebuild to skip that.)")
        pack_env = False
    out = build(Path(a.out), root=ROOT, include_env=pack_env, wheels=a.wheels, py=a.py)
    with zipfile.ZipFile(out) as z:
        n = len(z.namelist())
    print(f"{out}  ({n} files, {out.stat().st_size / 1e6:.1f} MB)")
    if pack_env:
        keys = ", ".join(sorted(_env_names(ROOT / ".env"))) or "nothing"
        print(f"Packed {ROOT / '.env'} (keys: {keys}).\nThis file now contains your credentials: keep it off public drives, repos and chats.")
    print('Upload it to /content in Colab, then run:  import runpy; runpy.run_path("/content/nisar_hub.pyz", run_name="__main__")')
    return 0


if __name__ == "__main__":
    sys.exit(main())
