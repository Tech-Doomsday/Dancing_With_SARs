#!/usr/bin/env python3
"""
Offline test for tools/extract_gunw.py using small SYNTHETIC HDF5 fixtures.

Run:  python3 tools/test_extract_gunw.py
Exit code 0 = all extractor behaviours verified.

The fixtures are generated by tools/make_synthetic_gunw_fixture.py into a
temporary directory; nothing here touches real science data, and the fixture
granule is labelled SYNTHETIC everywhere.
"""
import json
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
EXTRACT = os.path.join(ROOT, "tools", "extract_gunw.py")
MAKE = os.path.join(ROOT, "tools", "make_synthetic_gunw_fixture.py")

failures = []


def run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True)


def check(name, cond, detail=""):
    status = "pass" if cond else "FAIL"
    print(f"({status}) {name}" + (f" — {detail}" if detail and not cond else ""))
    if not cond:
        failures.append(name)


def main():
    tmp = tempfile.mkdtemp(prefix="motus-extractor-test-")
    try:
        good = os.path.join(tmp, "good.h5")
        run([sys.executable, MAKE, good])
        out = os.path.join(tmp, "derived")

        # 1. Valid synthetic product extracts successfully.
        r = run([sys.executable, EXTRACT, good, out, "--slug", "synthetic-test"])
        check("valid fixture extracts with exit 0", r.returncode == 0, r.stderr)
        meta_path = os.path.join(out, "meta.json")
        check("meta.json written", os.path.isfile(meta_path))
        meta = json.load(open(meta_path))

        # 2. Extracted grid matches the fixture.
        check("grid dims", meta["grid"]["width"] == 16 and meta["grid"]["height"] == 24)
        check("ySpacing negative (NISAR convention)", meta["grid"]["ySpacing"] < 0)
        check("polarization recorded", meta["radar"]["polarization"] == "HH")
        check("wavelength from centre frequency",
              abs(meta["radar"]["wavelength"] - 299792458.0 / 1.26999975e9) < 1e-6)
        check("iono screen variation extracted",
              meta["radar"]["ionoScreenVariationMadRad"] is not None)
        check("iono screen uncertainty extracted",
              meta["radar"]["ionoScreenUncertaintyMedianRad"] is not None)
        check("correction status recorded as not-applied",
              "not applied" in meta["processing"]["phaseIonosphericCorrectionAppliedToLayer"])
        for f in ("phase.f32", "coherence.f32", "components.u16"):
            p = os.path.join(out, f)
            check(f"{f} written", os.path.isfile(p))
        check("phase.f32 size matches grid",
              os.path.getsize(os.path.join(out, "phase.f32")) == 16 * 24 * 4)

        # 3. Corruption paths must fail with exit 2 and a clear message.
        cases = {
            "missing-layer": ["unwrappedPhase"],
            "bad-shape": ["shape"],
            "positive-dy": ["yCoordinateSpacing"],
            "bad-spec": ["specification"],
            "no-copol": ["co-pol"],
            "mismatched-coords": ["coordinate vectors"],
        }
        for kind, expect_words in cases.items():
            p = os.path.join(tmp, f"corrupt-{kind}.h5")
            run([sys.executable, MAKE, p, "--corrupt", kind])
            r = run([sys.executable, EXTRACT, p, os.path.join(tmp, f"out-{kind}"),
                     "--slug", f"corrupt-{kind}"])
            check(f"corrupt '{kind}' rejected with exit 2", r.returncode == 2,
                  f"exit={r.returncode} stderr={r.stderr[:200]}")
            check(f"corrupt '{kind}' message names the defect",
                  any(w.lower() in r.stderr.lower() for w in expect_words),
                  r.stderr[:200])

        # 4. Missing input file.
        r = run([sys.executable, EXTRACT, os.path.join(tmp, "nope.h5"), out])
        check("missing input file rejected", r.returncode == 2 and "not found" in r.stderr)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)

    print()
    if failures:
        print(f"FAILED: {len(failures)} checks: {failures}")
        return 1
    print("All extractor checks passed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
