def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def file_rows(base, names):
    rows = []
    for n in names:
        p = os.path.join(base, n)
        if os.path.exists(p):
            rows.append((n, os.path.getsize(p), sha256(p)))
        else:
            rows.append((n, None, None))
    return rows


def fmt_bytes(n):
    if n is None:
        return "—"
    for unit in ["B", "KiB", "MiB", "GiB"]:
        if n < 1024 or unit == "GiB":
            return f"{n:.1f} {unit}" if unit != "B" else f"{n} B"
        n /= 1024


